// The completion scripts of bash, zsh, fish and PowerShell, generated from the model (engine.ts): each
// carries the tree of the commands, their options with the kind of their values (an enumeration and
// its values, a file, a folder, a boolean, a dynamic value) and their positionals, and walks the words
// typed as engine.ts does. A dynamic value (a profile, a universe of the history…) is asked to
// `<program> __complete <words…>`, which reads local files only.
import { tree, type CompletionModel, type Kind, type OptionModel } from './engine.js';

export const SHELLS = ['bash', 'zsh', 'fish', 'pwsh'] as const;
export type Shell = (typeof SHELLS)[number];

const SAFE = /^[^\s,'"\\`$;|&<>(){}[\]*?#~]+$/;

/** A kind as the scripts read it: b (no value), v (free), e:<a,b> (an enumeration), f (a file), d (a folder), y:<source> (dynamic). */
export function kindToken(kind: Kind): string {
  switch (kind.type) {
    case 'none': return 'b';
    case 'enum': return kind.values.length && kind.values.every((v) => SAFE.test(v)) ? `e:${kind.values.join(',')}` : 'v';
    case 'file': return 'f';
    case 'dir': return 'd';
    case 'dynamic': return SAFE.test(kind.source) ? `y:${kind.source}` : 'v';
    default: return 'v';
  }
}

const describe = (text: string) => { const t = text.replace(/\s+/g, ' ').trim(); return t.length > 100 ? `${t.slice(0, 99)}…` : t; };
const ident = (program: string) => program.replace(/[^A-Za-z0-9]/g, '_');

type Row = { flag: string; token: string; description: string };
type Data = {
  children: { path: string; words: { word: string; description: string }[] }[];
  options: { command: string; rows: Row[] }[];
  globals: Row[];
  positionals: { command: string; tokens: string[] }[];
};

function rows(options: readonly OptionModel[]): Row[] {
  return options.flatMap((o) => o.flags.filter((f) => SAFE.test(f)).map((flag) => ({ flag, token: kindToken(o.kind), description: describe(o.description) })));
}

function data(model: CompletionModel): Data {
  const nodes = [...tree(model).values()];
  return {
    children: nodes.filter((n) => n.children.size).map((n) => ({ path: n.path, words: [...n.children].filter(([w]) => SAFE.test(w)).map(([word, d]) => ({ word, description: describe(d) })) })),
    options: model.commands.filter((c) => c.options.length).map((c) => ({ command: c.name, rows: rows(c.options) })),
    globals: rows(model.globals),
    positionals: model.commands.filter((c) => c.positionals.length).map((c) => ({ command: c.name, tokens: c.positionals.map((p) => `${kindToken(p.kind)}${p.rest ? '+' : ''}`) })),
  };
}

/** How a shell loads the script: the line, and where it goes. */
export function installation(program: string, shell: Shell): { line: string; where: string } {
  switch (shell) {
    case 'bash': return { line: `${program} completion bash > ~/.local/share/bash-completion/completions/${program}`, where: 'Run once (bash-completion loads the file); without bash-completion, add eval "$(' + program + ' completion bash)" to ~/.bashrc' };
    case 'zsh': return { line: `eval "$(${program} completion zsh)"`, where: 'Add to ~/.zshrc (after compinit, if it runs there)' };
    case 'fish': return { line: `${program} completion fish > ~/.config/fish/completions/${program}.fish`, where: 'Run once (fish loads the file)' };
    case 'pwsh': return { line: `${program} completion pwsh | Out-String | Invoke-Expression`, where: 'Add to the profile of PowerShell ($PROFILE); PowerShell 7.3 or later' };
  }
}

export function completionScript(model: CompletionModel, shell: Shell): string {
  const d = data(model);
  switch (shell) {
    case 'bash': return bash(model, d);
    case 'zsh': return zsh(model, d);
    case 'fish': return fish(model, d);
    case 'pwsh': return pwsh(model, d);
  }
}

const header = (model: CompletionModel, shell: Shell, comment = '#') => [
  `${comment} ${shell} completion of ${model.program} ${model.version}, generated by \`${model.program} completion ${shell}\` from its commands.`,
  `${comment} Install: ${installation(model.program, shell).line}`,
  `${comment} ${installation(model.program, shell).where}.`,
  `${comment} Dynamic values (profiles, recent universes and accounts, published themes) come from \`${model.program} __complete\`, which reads local files only.`,
];

// ---- bash (3.2 and later: no associative arrays) ----

const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

function bash(model: CompletionModel, d: Data): string {
  const f = `__${ident(model.program)}`;
  const optionLine = (r: Row) => sq(`${r.flag} ${r.token}`);
  return [
    ...header(model, 'bash'),
    '',
    `${f}_children() {`,
    '  case "$1" in',
    ...d.children.map((c) => `    ${sq(c.path)}) printf '%s\\n' ${c.words.map((w) => w.word).join(' ')} ;;`),
    '  esac',
    '}',
    `${f}_options() {`,
    '  case "$1" in',
    ...d.options.map((o) => `    ${sq(o.command)}) printf '%s\\n' ${o.rows.map(optionLine).join(' ')} ;;`),
    '  esac',
    `  printf '%s\\n' ${d.globals.map(optionLine).join(' ')}`,
    '}',
    `${f}_positionals() {`,
    '  case "$1" in',
    ...d.positionals.map((p) => `    ${sq(p.command)}) printf '%s\\n' ${p.tokens.join(' ')} ;;`),
    '  esac',
    '}',
    `${f}_kind() {`,
    '  local line',
    '  while IFS= read -r line; do',
    '    if [[ ${line%% *} == "$2" ]]; then printf \'%s\' "${line#* }"; return; fi',
    `  done < <(${f}_options "$1")`,
    '}',
    `${f}_is_child() {`,
    '  local word',
    '  while IFS= read -r word; do [[ $word == "$2" ]] && return 0; done < <(' + `${f}_children "$1")`,
    '  return 1',
    '}',
    `${f}() {`,
    '  local cur=${COMP_WORDS[COMP_CWORD]} node=\'\' pos=0 expect=\'\' dashes=\'\' word kind line words=\'\' i',
    '  COMPREPLY=()',
    '  for ((i = 1; i < COMP_CWORD; i++)); do',
    '    word=${COMP_WORDS[i]}',
    '    if [[ -n $expect ]]; then expect=\'\'; continue; fi',
    '    if [[ -n $dashes ]]; then pos=$((pos + 1)); continue; fi',
    '    if [[ $word == -- ]]; then dashes=1; continue; fi',
    '    if [[ $word == -?* ]]; then',
    '      [[ $word == *=* ]] && continue',
    `      kind=$(${f}_kind "$node" "$word")`,
    '      [[ -n $kind && $kind != b ]] && expect=$kind',
    '      continue',
    '    fi',
    `    if ((pos == 0)) && ${f}_is_child "$node" "$word"; then node=\${node:+$node }$word; continue; fi`,
    '    pos=$((pos + 1))',
    '  done',
    '  if [[ -z $expect && -z $dashes && $cur == -* ]]; then',
    `    while IFS= read -r line; do words+=" \${line%% *}"; done < <(${f}_options "$node")`,
    '    COMPREPLY=($(compgen -W "$words" -- "$cur"))',
    '    return',
    '  fi',
    '  if [[ -n $expect ]]; then',
    '    kind=$expect',
    '  else',
    `    [[ $pos == 0 && -z $dashes ]] && words=$(${f}_children "$node")`,
    `    local list=($(${f}_positionals "$node"))`,
    '    local n=${#list[@]}',
    '    kind=\'\'',
    '    if ((pos < n)); then kind=${list[pos]}; elif ((n > 0)) && [[ ${list[n - 1]} == *+ ]]; then kind=${list[n - 1]}; fi',
    '    kind=${kind%+}',
    '  fi',
    '  case $kind in',
    '    f) COMPREPLY=($(compgen -W "$words" -f -- "$cur")); compopt -o filenames 2>/dev/null; return ;;',
    '    d) COMPREPLY=($(compgen -W "$words" -d -- "$cur")); compopt -o filenames 2>/dev/null; return ;;',
    '    e:*) line=${kind#e:}; words+=" ${line//,/ }" ;;',
    // __complete answers the subcommands too: they replace the static ones.
    '    y:*) words=$("${COMP_WORDS[0]}" __complete "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null) ;;',
    '  esac',
    '  COMPREPLY=($(compgen -W "$words" -- "$cur"))',
    '}',
    `complete -F ${f} ${model.program}`,
    '',
  ].join('\n');
}

// ---- zsh ----

const zword = (s: string) => s.replace(/\\/g, '\\\\').replace(/:/g, '\\:');

function zsh(model: CompletionModel, d: Data): string {
  const f = `__${ident(model.program)}`;
  const main = `_${ident(model.program)}`;
  return [
    `#compdef ${model.program}`,
    ...header(model, 'zsh'),
    '',
    `${f}_children() {`,
    '  case "$1" in',
    ...d.children.map((c) => `    ${sq(c.path)}) print -rl -- ${c.words.map((w) => sq(`${zword(w.word)}:${w.description}`)).join(' ')} ;;`),
    '  esac',
    '}',
    `${f}_options() {`,
    '  case "$1" in',
    ...d.options.map((o) => `    ${sq(o.command)}) print -rl -- ${o.rows.map((r) => sq(`${r.flag} ${r.token} ${r.description}`)).join(' ')} ;;`),
    '  esac',
    `  print -rl -- ${d.globals.map((r) => sq(`${r.flag} ${r.token} ${r.description}`)).join(' ')}`,
    '}',
    `${f}_positionals() {`,
    '  case "$1" in',
    ...d.positionals.map((p) => `    ${sq(p.command)}) print -rl -- ${p.tokens.join(' ')} ;;`),
    '  esac',
    '}',
    `${main}() {`,
    '  local cur=${words[CURRENT]} node=\'\' expect=\'\' dashes=\'\' word kind line rest found',
    '  local -i pos=0 i n',
    '  local -a cands opts list vals',
    '  for (( i = 2; i < CURRENT; i++ )); do',
    '    word=${words[i]}',
    '    if [[ -n $expect ]]; then expect=\'\'; continue; fi',
    '    if [[ -n $dashes ]]; then pos+=1; continue; fi',
    '    if [[ $word == -- ]]; then dashes=1; continue; fi',
    '    if [[ $word == -?* ]]; then',
    '      [[ $word == *=* ]] && continue',
    '      kind=\'\'',
    `      for line in "\${(@f)$(${f}_options "$node")}"; do`,
    '        if [[ ${line%% *} == "$word" ]]; then rest=${line#* }; kind=${rest%% *}; break; fi',
    '      done',
    '      [[ -n $kind && $kind != b ]] && expect=$kind',
    '      continue',
    '    fi',
    '    if (( pos == 0 )); then',
    '      found=\'\'',
    `      for line in "\${(@f)$(${f}_children "$node")}"; do`,
    '        [[ ${line%%:*} == "$word" ]] && found=1',
    '      done',
    '      if [[ -n $found ]]; then node=${node:+$node }$word; continue; fi',
    '    fi',
    '    pos+=1',
    '  done',
    '  if [[ -z $expect && -z $dashes && $cur == -* ]]; then',
    `    for line in "\${(@f)$(${f}_options "$node")}"; do`,
    '      [[ -z $line ]] && continue',
    '      rest=${line#* }',
    '      [[ $rest == *\' \'* ]] && opts+=("${line%% *}:${rest#* }") || opts+=("${line%% *}")',
    '    done',
    '    _describe -t options option opts',
    '    return',
    '  fi',
    '  if [[ -n $expect ]]; then',
    '    kind=$expect',
    '  else',
    `    if (( pos == 0 )) && [[ -z $dashes ]]; then cands=("\${(@f)$(${f}_children "$node")}"); cands=(\${cands:#}); fi`,
    `    list=("\${(@f)$(${f}_positionals "$node")}"); list=(\${list:#})`,
    '    n=${#list}',
    '    kind=\'\'',
    '    if (( pos < n )); then kind=${list[pos + 1]}; elif (( n > 0 )) && [[ ${list[n]} == *+ ]]; then kind=${list[n]}; fi',
    '    kind=${kind%+}',
    '  fi',
    '  local ret=1',
    '  [[ $kind == y:* ]] && cands=()',
    '  (( ${#cands} )) && _describe -t commands command cands && ret=0',
    '  case $kind in',
    '    f) _files && ret=0 ;;',
    '    d) _files -/ && ret=0 ;;',
    '    e:*) vals=(${(s:,:)${kind#e:}}); compadd -a vals && ret=0 ;;',
    '    y:*) vals=("${(@f)$(${words[1]} __complete "${(@)words[2,CURRENT]}" 2>/dev/null)}"); vals=(${vals:#}); (( ${#vals} )) && compadd -a vals && ret=0 ;;',
    '  esac',
    '  return ret',
    '}',
    `if [[ \${funcstack[1]} == ${main} ]]; then`,
    `  ${main} "$@"`,
    'else',
    '  (( $+functions[compdef] )) || { autoload -Uz compinit && compinit; }',
    `  compdef ${main} ${model.program}`,
    'fi',
    '',
  ].join('\n');
}

// ---- fish ----

const fq = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function fish(model: CompletionModel, d: Data): string {
  const f = `__${ident(model.program)}`;
  return [
    ...header(model, 'fish'),
    '',
    `function ${f}_children`,
    '    switch "$argv[1]"',
    ...d.children.flatMap((c) => [`        case ${fq(c.path)}`, `            printf '%s\\t%s\\n' ${c.words.map((w) => `${fq(w.word)} ${fq(w.description)}`).join(' ')}`]),
    '    end',
    'end',
    `function ${f}_options`,
    '    switch "$argv[1]"',
    ...d.options.flatMap((o) => [`        case ${fq(o.command)}`, `            printf '%s\\t%s\\t%s\\n' ${o.rows.map((r) => `${fq(r.flag)} ${fq(r.token)} ${fq(r.description)}`).join(' ')}`]),
    '    end',
    `    printf '%s\\t%s\\t%s\\n' ${d.globals.map((r) => `${fq(r.flag)} ${fq(r.token)} ${fq(r.description)}`).join(' ')}`,
    'end',
    `function ${f}_positionals`,
    '    switch "$argv[1]"',
    ...d.positionals.flatMap((p) => [`        case ${fq(p.command)}`, `            printf '%s\\n' ${p.tokens.map(fq).join(' ')}`]),
    '    end',
    'end',
    `function ${f}_complete`,
    '    set -l tokens (commandline -opc)',
    '    set -l cur (commandline -ct)',
    '    set -l program $tokens[1]',
    '    set -e tokens[1]',
    '    set -l node \'\'',
    '    set -l pos 0',
    '    set -l expect \'\'',
    '    set -l dashes \'\'',
    '    for word in $tokens',
    '        if test -n "$expect"',
    '            set expect \'\'',
    '            continue',
    '        end',
    '        if test -n "$dashes"',
    '            set pos (math $pos + 1)',
    '            continue',
    '        end',
    '        if test "$word" = --',
    '            set dashes 1',
    '            continue',
    '        end',
    // fish 4 reads "?" literally (qmark-noglob): "-*" and not "-" alone.
    '        if string match -q -- \'-*\' "$word"; and test "$word" != -',
    '            string match -q -- \'*=*\' "$word"; and continue',
    `            for line in (${f}_options "$node")`,
    '                set -l parts (string split \\t -- $line)',
    '                if test "$parts[1]" = "$word"',
    '                    test "$parts[2]" != b; and set expect $parts[2]',
    '                    break',
    '                end',
    '            end',
    '            continue',
    '        end',
    '        if test $pos -eq 0',
    '            set -l found',
    `            for line in (${f}_children "$node")`,
    '                set -l parts (string split \\t -- $line)',
    '                test "$parts[1]" = "$word"; and set found 1',
    '            end',
    '            if set -q found[1]',
    '                if test -n "$node"',
    '                    set node "$node $word"',
    '                else',
    '                    set node $word',
    '                end',
    '                continue',
    '            end',
    '        end',
    '        set pos (math $pos + 1)',
    '    end',
    '    if test -z "$expect" -a -z "$dashes"; and string match -q -- \'-*\' "$cur"',
    `        for line in (${f}_options "$node")`,
    '            set -l parts (string split \\t -- $line)',
    '            printf \'%s\\t%s\\n\' $parts[1] $parts[3]',
    '        end',
    '        return',
    '    end',
    '    set -l kind $expect',
    '    if test -z "$expect"',
    `        set -l list (${f}_positionals "$node")`,
    '        set -l n (count $list)',
    '        set kind \'\'',
    '        if test $pos -lt $n',
    '            set kind $list[(math $pos + 1)]',
    '        else if test $n -gt 0; and string match -q -- \'*+\' $list[$n]',
    '            set kind $list[$n]',
    '        end',
    '        set kind (string replace -r -- \'\\+$\' \'\' "$kind")',
    '        if test $pos -eq 0 -a -z "$dashes"; and not string match -q -- \'y:*\' "$kind"',
    `            ${f}_children "$node"`,
    '        end',
    '    end',
    '    switch "$kind"',
    '        case f',
    '            __fish_complete_path "$cur"',
    '        case d',
    '            __fish_complete_directories "$cur"',
    '        case \'e:*\'',
    '            string split , -- (string sub -s 3 -- "$kind")',
    '        case \'y:*\'',
    '            $program __complete $tokens "$cur" 2>/dev/null',
    '    end',
    'end',
    `complete -c ${model.program} -f -a '(${f}_complete)'`,
    '',
  ].join('\n');
}

// ---- PowerShell (7.3 and later) ----

const pq = (s: string) => `'${s.replace(/'/g, "''")}'`;

function pwsh(model: CompletionModel, d: Data): string {
  const table = (entries: { key: string; values: string[] }[]) => entries.map((e) => `        ${pq(e.key)} = @(${e.values.map(pq).join(', ')})`);
  return [
    ...header(model, 'pwsh'),
    '',
    `Register-ArgumentCompleter -Native -CommandName @(${pq(model.program)}, ${pq(`${model.program}.exe`)}) -ScriptBlock {`,
    '    param($wordToComplete, $commandAst, $cursorPosition)',
    '    $children = @{',
    ...table(d.children.map((c) => ({ key: c.path, values: c.words.map((w) => `${w.word}|${w.description}`) }))),
    '    }',
    '    $options = @{',
    ...table(d.options.map((o) => ({ key: o.command, values: o.rows.map((r) => `${r.flag}|${r.token}|${r.description}`) }))),
    '    }',
    `    $globals = @(${d.globals.map((r) => pq(`${r.flag}|${r.token}|${r.description}`)).join(', ')})`,
    '    $positionals = @{',
    ...table(d.positionals.map((p) => ({ key: p.command, values: p.tokens }))),
    '    }',
    '    $elements = @($commandAst.CommandElements | Where-Object { $_.Extent.StartOffset -lt $cursorPosition } | ForEach-Object {',
    '        if ($_ -is [System.Management.Automation.Language.StringConstantExpressionAst]) { $_.Value } else { $_.Extent.Text }',
    '    })',
    '    $program = $elements[0]',
    '    $last = $elements.Count - 1',
    '    if ($wordToComplete -ne \'\' -and $last -ge 1) { $last-- }',
    '    $before = @()',
    '    for ($i = 1; $i -le $last; $i++) { $before += [string]$elements[$i] }',
    '    $optionsOf = { param($n) $all = @(); if ($options.ContainsKey($n)) { $all += $options[$n] }; $all + $globals }',
    '    $node = \'\'; $pos = 0; $expect = \'\'; $dashes = $false',
    '    foreach ($word in $before) {',
    '        if ($expect -ne \'\') { $expect = \'\'; continue }',
    '        if ($dashes) { $pos++; continue }',
    '        if ($word -ceq \'--\') { $dashes = $true; continue }',
    '        if ($word.Length -gt 1 -and $word.StartsWith(\'-\')) {',
    '            if ($word.Contains(\'=\')) { continue }',
    '            foreach ($o in (& $optionsOf $node)) {',
    '                $parts = $o -split \'\\|\', 3',
    '                if ($parts[0] -ceq $word) { if ($parts[1] -ne \'b\') { $expect = $parts[1] }; break }',
    '            }',
    '            continue',
    '        }',
    '        if ($pos -eq 0 -and $children.ContainsKey($node)) {',
    '            $found = $false',
    '            foreach ($c in $children[$node]) { if (($c -split \'\\|\', 2)[0] -ceq $word) { $found = $true } }',
    '            if ($found) { $node = $(if ($node) { "$node $word" } else { $word }); continue }',
    '        }',
    '        $pos++',
    '    }',
    '    $results = [System.Collections.Generic.List[System.Management.Automation.CompletionResult]]::new()',
    '    $add = {',
    '        param($value, $description, $type)',
    '        if ($value -and $value.StartsWith($wordToComplete, [System.StringComparison]::OrdinalIgnoreCase)) {',
    '            $tip = $(if ($description) { $description } else { $value })',
    '            $results.Add([System.Management.Automation.CompletionResult]::new($value, $value, $type, $tip))',
    '        }',
    '    }',
    '    if ($expect -eq \'\' -and -not $dashes -and $wordToComplete.StartsWith(\'-\')) {',
    '        foreach ($o in (& $optionsOf $node)) { $parts = $o -split \'\\|\', 3; & $add $parts[0] $parts[2] \'ParameterName\' }',
    '        return $results',
    '    }',
    '    $kind = $expect',
    '    if ($expect -eq \'\') {',
    '        $list = @($(if ($positionals.ContainsKey($node)) { $positionals[$node] }))',
    '        $kind = \'\'',
    '        if ($pos -lt $list.Count) { $kind = $list[$pos] } elseif ($list.Count -gt 0 -and $list[-1].EndsWith(\'+\')) { $kind = $list[-1] }',
    '        $kind = $kind.TrimEnd(\'+\')',
    '        if ($pos -eq 0 -and -not $dashes -and -not $kind.StartsWith(\'y:\') -and $children.ContainsKey($node)) {',
    '            foreach ($c in $children[$node]) { $parts = $c -split \'\\|\', 2; & $add $parts[0] $parts[1] \'Command\' }',
    '        }',
    '    }',
    '    if ($kind -eq \'f\' -or $kind -eq \'d\') {',
    '        if ($results.Count -eq 0) { return }',
    '        Get-ChildItem -Path "$wordToComplete*" -Directory:($kind -eq \'d\') -ErrorAction SilentlyContinue | ForEach-Object { & $add $_.Name $_.FullName \'ProviderItem\' }',
    '    } elseif ($kind.StartsWith(\'e:\')) {',
    '        foreach ($v in $kind.Substring(2).Split(\',\')) { & $add $v $null \'ParameterValue\' }',
    '    } elseif ($kind.StartsWith(\'y:\')) {',
    '        foreach ($v in @(& $program __complete @before $wordToComplete 2>$null)) { & $add ([string]$v) $null \'ParameterValue\' }',
    '    }',
    '    return $results',
    '}',
    '',
  ].join('\n');
}
