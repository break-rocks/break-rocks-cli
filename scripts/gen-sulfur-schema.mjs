#!/usr/bin/env node
// Generates src/sulfur/schema.generated.ts from the schema native-sulfur serves
// (schema/sulfur/server.graphql, written by npm run update:sulfur-schema from the server's API_SDL): the compact form of
// src/api/sdl.ts, read at run time by the seam (src/sulfur/fit.ts) that fits the CLI's documents (API v2, talc) to what
// the server serves. Usage: node scripts/gen-sulfur-schema.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from './gen-schema-lib.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const out = `${root}src/sulfur/schema.generated.ts`;
const schema = parse(readFileSync(`${root}schema/sulfur/server.graphql`, 'utf8'));
try { schema.version = readFileSync(`${root}schema/sulfur/VERSION`, 'utf8').trim(); } catch { /* none */ }
delete schema.deprecated;
const text = `// Generated by scripts/gen-sulfur-schema.mjs from schema/sulfur/server.graphql (native-sulfur's API): do not edit.
// Compact form (src/api/sdl.ts): types[name] = { k, f: { field: [type, args?] }, v }.
import type { Sdl } from '../api/sdl.js';

export const SERVER: Sdl = ${JSON.stringify(schema)};
`;
if (check) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* absent */ }
  if (current !== text) { console.error('src/sulfur/schema.generated.ts is not the one of schema/sulfur: npm run gen:sulfur-schema'); process.exit(1); }
  console.log('src/sulfur/schema.generated.ts is current');
} else {
  writeFileSync(out, text);
  console.log(`src/sulfur/schema.generated.ts: ${Object.keys(schema.types).length} types, ${Object.keys(schema.query).length} queries, ${Object.keys(schema.mutation).length} mutations`);
}
