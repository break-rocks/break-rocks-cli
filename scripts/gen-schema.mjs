#!/usr/bin/env node
// Generates src/api/schema.generated.ts from the published contract (schema/schema.graphql):
// the object, input and enum types, the queries and the mutations with their arguments, in a compact
// form the CLI reads at run time to build its selections, its variables and the JSON Schemas of its
// commands. Run after an update of schema/schema.graphql: npm run gen:schema (test/api.test.ts checks it is current).
// Usage: node scripts/gen-schema.mjs [schema.graphql] [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from './gen-schema-lib.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const args = process.argv.slice(2);
const check = args.includes('--check');
const source = args.find((a) => !a.startsWith('--')) ?? `${root}schema/schema.graphql`;
const out = `${root}src/api/schema.generated.ts`;

const schema = parse(readFileSync(source, 'utf8'));
const text = `// Generated by scripts/gen-schema.mjs from schema/schema.graphql: do not edit.
// Compact form: types[name] = { k: 'o' (object) | 'i' (input) | 'e' (enum) | 'u' (union) | 's' (scalar), f: { field: [type, args?] }, v: values }.
import type { Sdl } from './sdl.js';

export const SCHEMA: Sdl = ${JSON.stringify(schema)};
`;
if (check) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* absent */ }
  if (current !== text) { console.error('src/api/schema.generated.ts is not the one of schema/schema.graphql: npm run gen:schema'); process.exit(1); }
  console.log('src/api/schema.generated.ts is current');
} else {
  writeFileSync(out, text);
  console.log(`src/api/schema.generated.ts: ${Object.keys(schema.types).length} types, ${Object.keys(schema.query).length} queries, ${Object.keys(schema.mutation).length} mutations`);
}
